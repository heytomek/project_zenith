import type { Claim, Effect, Profile, ResourceUse } from "./types";

function claim(
  id: string,
  scopeId: string,
  label: string,
  value: number,
  unit: string,
  status: Claim["status"],
  min: number,
  max: number,
  step: number,
  title: string,
  author: string,
  date: string,
  excerpt: string,
  dissent?: string,
): Claim {
  return {
    id,
    scopeId,
    label,
    value,
    unit,
    status,
    min,
    max,
    step,
    source: { title, author, date, excerpt },
    ...(dissent ? { dissent } : {}),
  };
}
const resource = (
  capabilityId: string,
  amount: number,
  scaleClaimId?: string,
  scaleBase?: number,
): ResourceUse => ({
  capabilityId,
  amount,
  ...(scaleClaimId ? { scaleClaimId, scaleBase } : {}),
});
const effect = (
  objectiveId: string,
  amount: number,
  scaleClaimId?: string,
  scaleBase?: number,
): Effect => ({
  objectiveId,
  amount,
  ...(scaleClaimId ? { scaleClaimId, scaleBase } : {}),
});

